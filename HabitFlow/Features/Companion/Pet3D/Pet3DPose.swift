import Foundation

/// Поза 3D-питомца на один кадр: всё, что сцена передаёт в SceneKit.
/// Считается в SwiftUI (физика PetSim + мозг PetBrain), SceneKit только рисует.
struct Pet3DPose {
    /// Время в секундах (для лёгких «само по себе» движений: хвост, уши, покачивание).
    var time = 0.0
    /// Целевое лицо от мозга питомца; плавно подводится внутри модели.
    var face = PetFace()
    /// Растяжение корпуса от основания (1 — без изменений).
    var sx = 1.0
    var sy = 1.0
    /// Крен в градусах, как в SwiftUI (положительный — по часовой).
    var roll = 0.0
    /// Оборот вокруг вертикальной оси в градусах (сальто-разворот: видна и спинка).
    var spin = 0.0
    /// Наклон телефона −1…1: корпус слегка поворачивается вслед.
    var turn = 0.0
    /// Упругая отдача от касания (−1…1) и сторона касания (−0.5…0.5).
    var wobble = 0.0
    var wobbleSide = 0.0
    /// 0…1 — спит.
    var sleepiness = 0.0
}
